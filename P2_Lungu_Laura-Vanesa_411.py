"""### 4.3. BoVW + TF-IDF + Color Histogram

Each image is represented as a histogram of visual words (BoVW). TF-IDF weighting is applied to reduce the impact of very frequent, less informative visual words. Finally, the BoVW representation is combined with a global HSV color histogram.
"""

import numpy as np
import cv2
from sklearn.feature_extraction.text import TfidfTransformer
from sklearn.preprocessing import normalize

def build_bovw(desc_list, kmeans):
    vocab_size = kmeans.n_clusters
    hists = []

    for desc in desc_list:
        words = kmeans.predict(desc)
        hist, _ = np.histogram(words, bins=np.arange(vocab_size + 1))
        hist = hist.astype(np.float32)

        if hist.sum() > 0:
            hist /= hist.sum()  # L1

        hists.append(hist)

    return np.asarray(hists)

def hsv_hist(images, bins=32):
    feats = []
    for img in images:
        hsv = cv2.cvtColor(img, cv2.COLOR_RGB2HSV)
        h = cv2.calcHist([hsv], [0], None, [bins], [0, 180])
        s = cv2.calcHist([hsv], [1], None, [bins], [0, 256])
        v = cv2.calcHist([hsv], [2], None, [bins], [0, 256])

        hist = np.concatenate([h, s, v]).flatten().astype(np.float32)
        if hist.sum() > 0:
            hist /= hist.sum()  # L1

        feats.append(hist)

    return np.asarray(feats)

print("Building BoVW histograms...")
