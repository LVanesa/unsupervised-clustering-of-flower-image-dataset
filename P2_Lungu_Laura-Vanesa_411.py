"""# 3. Feature Set 1: HOG + LBP + Color Histograms

**Feature components:**
- **HOG (Histogram of Oriented Gradients)**  
  Used to capture shape and edge information. HOG encodes local gradient orientations and is effective at describing object structure and contours.

- **LBP (Local Binary Patterns)**  
  Used to capture local texture information. LBP describes small-scale intensity variations and helps model surface patterns such as petals and internal flower textures.

- **HSV Color Histograms**  
  Used to represent the color distribution of each image. The HSV color space provides a more robust separation of color information compared to RGB, which is important for flower images.

**Feature processing:**
- Each feature type is extracted independently.
- HOG features are standardized using `StandardScaler`.
- LBP and color histograms are L2-normalized.
- The final feature vector is obtained by concatenating the three feature blocks, with a higher weight assigned to HOG and smaller weights assigned to LBP and color features.

This combined representation is used as input for the clustering algorithms evaluated in the following sections.

"""

import numpy as np
import cv2
from skimage.feature import hog, local_binary_pattern
from sklearn.preprocessing import StandardScaler, normalize

def extract_hog(images, orientations=9, pixels_per_cell=(16, 16), cells_per_block=(2, 2), log_every=200):
    feats = []
    for i, img in enumerate(images):
        gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
        f = hog(
            gray,
            orientations=orientations,
            pixels_per_cell=pixels_per_cell,
            cells_per_block=cells_per_block,
            block_norm="L2-Hys",
            transform_sqrt=True,
            feature_vector=True
        )
        feats.append(f)
        if log_every and (i + 1) % log_every == 0:
            print(f"HOG: {i + 1}/{len(images)}")
    return np.asarray(feats)

def extract_lbp(images, radius=2, n_points=16, log_every=200):
    feats = []
    n_bins = n_points + 2  # for 'uniform'
    for i, img in enumerate(images):
        gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
        lbp = local_binary_pattern(gray, n_points, radius, method="uniform")
        hist, _ = np.histogram(lbp.ravel(), bins=n_bins, range=(0, n_bins))
        hist = hist.astype(np.float32)
        if hist.sum() > 0:
            hist /= hist.sum()
        feats.append(hist)
        if log_every and (i + 1) % log_every == 0:
            print(f"LBP: {i + 1}/{len(images)}")
    return np.asarray(feats)

def extract_hsv_hist(images, bins=32, log_every=200):
    feats = []
    for i, img in enumerate(images):
        hsv = cv2.cvtColor(img, cv2.COLOR_RGB2HSV)
        h = cv2.calcHist([hsv], [0], None, [bins], [0, 180])
        s = cv2.calcHist([hsv], [1], None, [bins], [0, 256])
        v = cv2.calcHist([hsv], [2], None, [bins], [0, 256])
        hist = np.concatenate([h, s, v]).flatten().astype(np.float32)
        if hist.sum() > 0:
            hist /= hist.sum()
        feats.append(hist)
        if log_every and (i + 1) % log_every == 0:
            print(f"Color: {i + 1}/{len(images)}")
    return np.asarray(feats)

def build_features(images_train, images_val, images_test, weights=(0.6, 0.2, 0.2)):
    w_hog, w_lbp, w_col = weights

    print("Extracting HOG...")
    hog_train = extract_hog(images_train)
    hog_val   = extract_hog(images_val, log_every=0)
    hog_test  = extract_hog(images_test, log_every=0)

    print("Extracting LBP...")
    lbp_train = extract_lbp(images_train)
    lbp_val   = extract_lbp(images_val, log_every=0)
    lbp_test  = extract_lbp(images_test, log_every=0)

    print("Extracting Color...")
    col_train = extract_hsv_hist(images_train)
    col_val   = extract_hsv_hist(images_val, log_every=0)
    col_test  = extract_hsv_hist(images_test, log_every=0)

    # Normalize each block
    hog_scaler = StandardScaler()
    hog_train = hog_scaler.fit_transform(hog_train)
    hog_val   = hog_scaler.transform(hog_val)
    hog_test  = hog_scaler.transform(hog_test)

    lbp_train = normalize(lbp_train, norm="l2")
    lbp_val   = normalize(lbp_val, norm="l2")
    lbp_test  = normalize(lbp_test, norm="l2")

    col_train = normalize(col_train, norm="l2")
    col_val   = normalize(col_val, norm="l2")
    col_test  = normalize(col_test, norm="l2")

    # Weighted concatenation
    X_train = np.hstack([hog_train * w_hog, lbp_train * w_lbp, col_train * w_col])
    X_val   = np.hstack([hog_val   * w_hog, lbp_val   * w_lbp, col_val   * w_col])
    X_test  = np.hstack([hog_test  * w_hog, lbp_test  * w_lbp, col_test  * w_col])

    X_train = np.nan_to_num(X_train)
    X_val   = np.nan_to_num(X_val)
    X_test  = np.nan_to_num(X_test)

    print("\nFeature sizes:")
    print(f"  HOG:   {hog_train.shape[1]}")
    print(f"  LBP:   {lbp_train.shape[1]}")
    print(f"  Color: {col_train.shape[1]}")
    print(f"  Total: {X_train.shape[1]}")
    print("Final matrices:", X_train.shape, X_val.shape, X_test.shape)

    return X_train, X_val, X_test

# Build final feature matrices
features_train, features_val, features_test = build_features(
    images_train, images_val, images_test,
    weights=(0.6, 0.2, 0.2)
)

"""## 3.1. Evaluation Metrics & Helper Functions"""

import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.metrics import (
    confusion_matrix,
    silhouette_score,
    adjusted_rand_score,
    normalized_mutual_info_score
)
from scipy.optimize import linear_sum_assignment


def cluster_accuracy(y_true, y_pred):
    """Cluster-to-label accuracy using Hungarian matching."""
    cm = confusion_matrix(y_true, y_pred)
    row_ind, col_ind = linear_sum_assignment(-cm)
    return cm[row_ind, col_ind].sum() / len(y_true)


def evaluate_clustering(y_true, y_pred, X, name=""):
    """Print and return common clustering metrics (Acc, ARI, NMI, Silhouette)."""
    acc = cluster_accuracy(y_true, y_pred)
    ari = adjusted_rand_score(y_true, y_pred)
    nmi = normalized_mutual_info_score(y_true, y_pred)

    # Silhouette needs at least 2 clusters
    sil = -1.0
    if len(np.unique(y_pred)) > 1:
        sil = silhouette_score(X, y_pred)

    if name:
        print(f"\nRESULTS: {name}")
    else:
        print("\nRESULTS")

    print(f"  Accuracy:   {acc*100:.2f}%")
    print(f"  ARI:        {ari:.4f}")
    print(f"  NMI:        {nmi:.4f}")
    print(f"  Silhouette: {sil:.4f}")

    return {"accuracy": acc, "ari": ari, "nmi": nmi, "silhouette": sil}


def plot_confusion_matrix(y_true, y_pred, label_names, title="Confusion Matrix"):
    """Confusion matrix: true labels vs predicted clusters."""
    cm = confusion_matrix(y_true, y_pred)

    plt.figure(figsize=(7, 5))
    sns.heatmap(
        cm,
        annot=True,
        fmt="d",
        cmap="Blues",
        xticklabels=[f"Cluster {i}" for i in range(cm.shape[1])],
        yticklabels=[label_names[i] for i in range(cm.shape[0])]
    )
    plt.xlabel("Predicted cluster")
    plt.ylabel("True label")
    plt.title(title)
    plt.tight_layout()
    plt.show()

"""## 3.2 BIRCH Hyperparameter Tuning (Validation Search)

Here I tune BIRCH using the validation set.  
I try a few PCA dimensions (to reduce noise / dimensionality) and several BIRCH `threshold` values (which controls how aggressively BIRCH merges points into subclusters).  

For each configuration, I fit BIRCH on the training features and evaluate on the validation split using:
- **Accuracy (Hungarian matching)**,
- **ARI** (main metric for clustering quality),
- **Silhouette** (cluster separation in feature space).

"""

import numpy as np
from sklearn.cluster import Birch
from sklearn.decomposition import PCA
from sklearn.metrics import adjusted_rand_score, silhouette_score

PCA_DIMS = [None, 30, 50, 100, 150]
THRESHOLDS = [0.3, 0.5, 0.7, 1.0, 1.5]

results = []

for pca_dim in PCA_DIMS:
    # PCA is fitted only on train, then applied to val
    if pca_dim is not None:
        pca = PCA(n_components=pca_dim, random_state=42)
        X_train = pca.fit_transform(features_train)
        X_val = pca.transform(features_val)
    else:
        X_train = features_train
        X_val = features_val

    for thr in THRESHOLDS:
        birch = Birch(n_clusters=3, threshold=thr)
        birch.fit(X_train)
        y_val_pred = birch.predict(X_val)

        # Skip bad cases (everything in one cluster)
        if len(np.unique(y_val_pred)) < 2:
            continue

        acc = cluster_accuracy(labels_val, y_val_pred)
        ari = adjusted_rand_score(labels_val, y_val_pred)
        sil = silhouette_score(X_val, y_val_pred)

        results.append({
            "pca_dim": pca_dim,
            "threshold": thr,
            "accuracy": acc,
            "ari": ari,
            "silhouette": sil
        })

# Sort by ARI (best overall clustering agreement)
results = sorted(results, key=lambda r: r["ari"], reverse=True)

