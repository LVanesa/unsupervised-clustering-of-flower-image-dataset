def center_crop_and_resize(img, target_size=(128, 128)):
    # crop center to get a square image, then resize to target_size
    h, w = img.shape[:2]

    if h > w:
        # too tall -> cut top and bottom
        start = (h - w) // 2
        img = img[start:start + w, :]
    elif w > h:
        # too wide -> cut left and right
        start = (w - h) // 2
        img = img[:, start:start + h]

    img = cv2.resize(img, target_size)
    return img

def load_images_and_labels(data_path, classes, target_size=(128, 128)):
    images = []
    labels = []
    file_paths = []

    label_names = {i: name for i, name in enumerate(classes)}
    valid_extension = (".jpg", ".jpeg", ".png")

    for label_idx, class_name in enumerate(classes):
        folder = os.path.join(data_path, class_name)

        if not os.path.exists(folder):
            print("Folder not found:", folder)
            continue

        files = [f for f in os.listdir(folder) if f.lower().endswith(valid_extension)]
        print(f"Loading {class_name}: {len(files)} files...")

        for f in files:
            fp = os.path.join(folder, f)

            img = cv2.imread(fp)
            if img is None:
                continue

            img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
            img = center_crop_and_resize(img, target_size)

            images.append(img)
            labels.append(label_idx)
            file_paths.append(fp)

    images = np.array(images)
    labels = np.array(labels)

    return images, labels, label_names, file_paths


