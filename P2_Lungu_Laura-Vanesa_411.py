"""# 4. Feature Set 2: Dense SIFT + Bag of Visual Words (BoVW) + Color Histogram
This feature set is based on local keypoint descriptors and a Bag of Visual Words (BoVW) representation.
Compared to Feature Set 1, this approach captures more fine-grained local structure, at the cost of higher
computational complexity.

1) extract **Dense SIFT descriptors** on a regular grid (same keypoints for all images),  
2) build a **visual vocabulary** with MiniBatchKMeans,  
3) represent each image as a **BoVW histogram** (TF-IDF weighted),  
4) concatenate BoVW with a simple **HSV color histogram**.

### 4.1. Dense SIFT Descriptors

Instead of detecting keypoints automatically, Dense SIFT extracts SIFT descriptors on a regular grid.
This ensures that all images are represented consistently and that local patterns are captured across
the entire image, not only around high-contrast regions.
"""

import cv2
import numpy as np

def extract_dense_sift(images, step=16, patch=48, print_every=200):
    sift = cv2.SIFT_create(
        nfeatures=0,
        contrastThreshold=0.01,
        edgeThreshold=15
    )

    h, w = images[0].shape[:2]
    keypoints = [
        cv2.KeyPoint(float(x), float(y), float(patch))
        for y in range(patch // 2, h - patch // 2, step)
        for x in range(patch // 2, w - patch // 2, step)
    ]

    print(f"Dense SIFT: step={step}, patch={patch} -> {len(keypoints)} keypoints/image")

    desc_list = []
    for i, img in enumerate(images):
        if print_every and i % print_every == 0:
            print(f"  processed {i}/{len(images)}")

        gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
        _, desc = sift.compute(gray, keypoints)

        if desc is None or len(desc) == 0:
            desc = np.zeros((1, 128), dtype=np.float32)

        desc_list.append(desc)

    return desc_list

# Extract descriptors per split
desc2_train = extract_dense_sift(images_train, step=16, patch=48)
desc2_val   = extract_dense_sift(images_val,   step=16, patch=48, print_every=0)
desc2_test  = extract_dense_sift(images_test,  step=16, patch=48, print_every=0)

def desc_stats(desc_list, n_imgs):
    total = sum(d.shape[0] for d in desc_list)
    return total, total / n_imgs

train_total, train_avg = desc_stats(desc2_train, len(images_train))
val_total,   val_avg   = desc_stats(desc2_val,   len(images_val))
